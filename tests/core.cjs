const assert = require('node:assert/strict');
const ts = require('typescript');
const fs = require('node:fs');
const Module = require('node:module');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, filename);
let stored = null;
let failSave = false;
const originalLoad = Module._load;
Module._load = function (id, ...args) {
  if (id === '@react-native-async-storage/async-storage') return { getItem: async () => stored, setItem: async (_, value) => { if (failSave) throw new Error('disk full'); stored = value; } };
  return originalLoad.call(this, id, ...args);
};
const { initialState, transition, completeDue, remaining, getStats, localDateKey } = require('../src/utils/model.ts');
const { saveState, loadState, validateState } = require('../src/storage/storage.ts');
async function run() {
  let state = initialState();
  state = transition(state, { type: 'start' }, 1000, 'session-1');
  assert.equal(remaining(state.timer, 11000), 1490);
  state = transition(state, { type: 'pause' }, 11000);
  assert.equal(remaining(state.timer, 999999), 1490);
  assert.throws(() => transition(state, { type: 'subject', id: 'general' }));
  state = transition(state, { type: 'start' }, 21000);
  assert.equal(state.timer.endsAt, 1511000);
  await saveState(state);
  state = completeDue(await loadState(), 2000000);
  assert.equal(state.sessions.length, 1);
  assert.equal(state.sessions[0].completedAt, 1511000);
  assert.equal(completeDue(state, 3000000), state);
  assert.equal(transition(state, { type: 'reset' }).sessions.length, 1);
  let reset = transition(initialState(), { type: 'start' }, 1000);
  reset = transition(reset, { type: 'reset' }, 2000);
  assert.equal(completeDue(reset, 9999999).sessions.length, 0);
  for (let i = 0; i < 3; i++) {
    state = transition(state, { type: 'mode', mode: 'focus' });
    state = transition(state, { type: 'start' }, 4000000 + i * 2000000, `session-${i + 2}`);
    state = completeDue(state, state.timer.endsAt);
  }
  assert.equal(state.cycle, 4);
  state = transition(state, { type: 'mode', mode: 'longBreak' });
  state = transition(state, { type: 'start' }, 12000000);
  state = completeDue(state, state.timer.endsAt);
  assert.equal(state.cycle, 0);
  assert.equal(state.sessions.length, 4);
  state = transition(state, { type: 'saveSubject', name: 'Math' }, 13000000, 'math');
  state = transition(state, { type: 'deleteSubject', id: 'general' });
  assert.equal(state.sessions[0].subjectName, 'Fokus umum');
  assert.throws(() => transition(state, { type: 'saveSubject', name: '   ' }));
  assert.throws(() => transition(state, { type: 'settings', settings: { ...state.settings, focusMinutes: 0 } }));
  const now = new Date(2026, 10, 14, 12).getTime();
  const sessions = [0, 1, 2].map(offset => ({ ...state.sessions[0], id: String(offset), completedAt: new Date(2026, 10, 14 - offset, 0, 1).getTime() }));
  assert.equal(getStats(sessions, now).streak, 3);
  assert.equal(getStats(sessions, now).todaySessions, 1);
  assert.equal(getStats(sessions, now).week.length, 7);
  assert.equal(getStats(sessions, now).week[6].key, localDateKey(now));
  assert.equal(getStats([], now).streak, 0);
  assert.equal(validateState(state), true);
  await saveState(state);
  assert.deepEqual(await loadState(), state);
  failSave = true;
  await assert.rejects(saveState(initialState()), /disk full/);
  failSave = false;
  assert.deepEqual(await loadState(), state);
  stored = '{broken';
  await assert.rejects(loadState());
  stored = '{}';
  await assert.rejects(loadState(), /tidak valid/);
  console.log('PASS timer, restore, deduplication, reset, break cycle, subjects, settings, local stats, storage failures');
}
run().catch(error => { console.error(error); process.exitCode = 1; });
